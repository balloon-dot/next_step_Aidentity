const qualityName=s=>String(s).toLowerCase().replace(/ё/g,'е').replace(/\s+/g,' ').trim();
const synonymCache=new WeakMap();
// All synonyms of quality q in cluster c, without duplicates and without the quality itself: [cluster, quality], own cluster first.
export function synonymsOf(catalog,c,q){
 if(!synonymCache.has(catalog)){const at=new Map(),map=new Map();catalog.clusters.forEach((x,ci)=>x.qualities.forEach((y,qi)=>at.set(qualityName(y.name),ci+':'+qi)));
  for(const names of ADJACENT_FAMILIES){const keys=names.map(n=>at.get(qualityName(n))).filter(Boolean);for(const k of keys){if(!map.has(k))map.set(k,[]);for(const o of keys)if(o!==k&&!map.get(k).includes(o))map.get(k).push(o)}}
  synonymCache.set(catalog,map)}
 const list=(synonymCache.get(catalog).get(c+':'+q)||[]).map(k=>k.split(':').map(Number));
 return [...list.filter(x=>x[0]===c),...list.filter(x=>x[0]!==c)];
}
// Sets quality j of cluster i to v; the other qualities of the cluster share the rest of its budget.
export function placeQuality(d,i,j,v){
 const q=d.qualities[i],budget=qualityBudget(d,i),free=q.map((_,k)=>k).filter(k=>k!==j);
 v=free.length?Math.max(MIN_WEIGHT,Math.min(budget-free.length*MIN_WEIGHT,v)):budget;
 const other=distribute(free.map(k=>q[k]),budget-v,MIN_WEIGHT);
 q[j]=v;free.forEach((k,n)=>q[k]=other[n]);return v;
}
